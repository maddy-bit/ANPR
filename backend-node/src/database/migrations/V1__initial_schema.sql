-- 1. PostGIS Spatial Extension
CREATE EXTENSION IF NOT EXISTS postgis;

-- 2. Cameras Table (Surveillance Nodes)
CREATE TABLE cameras (
    id VARCHAR(255) PRIMARY KEY,
    name VARCHAR(255),
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    direction VARCHAR(255),
    status VARCHAR(255),
    video_source VARCHAR(255),
    location geography(Point, 4326) GENERATED ALWAYS AS (
        ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)::geography
    ) STORED
);

-- GiST Spatial Index for high-performance radius (ST_DWithin) and nearest-neighbor (KNN) queries
CREATE INDEX idx_cameras_location ON cameras USING GIST (location);

-- 3. Vehicles Table (Target Identities)
CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate VARCHAR(255) NOT NULL,
    vehicle_type VARCHAR(255),
    color VARCHAR(255),
    make VARCHAR(255),
    model VARCHAR(255),
    CONSTRAINT uk_vehicles_plate UNIQUE (plate)
);

CREATE INDEX idx_vehicles_plate ON vehicles (plate);

-- 4. Vehicle Detections Table (Raw Multi-Camera Evidence Logs)
-- vehicle_id is nullable to preserve raw evidence frames even when OCR cannot read the plate
CREATE TABLE vehicle_detections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT,
    camera_id VARCHAR(255) NOT NULL,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    direction VARCHAR(255),
    speed_kmh DOUBLE PRECISION,
    vehicle_class VARCHAR(255),
    detection_confidence DOUBLE PRECISION,
    plate_confidence DOUBLE PRECISION,
    plate_text_raw VARCHAR(255),
    plate_text_normalized VARCHAR(255),
    reid_confidence DOUBLE PRECISION,
    reid_embedding TEXT,
    image_path VARCHAR(255),
    track_id INTEGER,
    frame_number INTEGER,
    location geography(Point, 4326) GENERATED ALWAYS AS (
        ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)::geography
    ) STORED,
    CONSTRAINT fk_detection_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id) ON DELETE SET NULL,
    CONSTRAINT fk_detection_camera FOREIGN KEY (camera_id) REFERENCES cameras (id) ON DELETE RESTRICT
);

-- Compound indexes for trajectory reconstruction & forensic lookups
CREATE INDEX idx_detection_camera_time ON vehicle_detections (camera_id, timestamp);
CREATE INDEX idx_detection_vehicle_time ON vehicle_detections (vehicle_id, timestamp);
CREATE INDEX idx_vehicle_detections_location ON vehicle_detections USING GIST (location);

-- 5. Audit Log Entries Table (Legal & Compliance Access Logs)
CREATE TABLE audit_log_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMP WITH TIME ZONE,
    action VARCHAR(255),
    plate VARCHAR(255),
    remote_address VARCHAR(255)
);

CREATE INDEX idx_audit_log_timestamp ON audit_log_entries (timestamp DESC);

